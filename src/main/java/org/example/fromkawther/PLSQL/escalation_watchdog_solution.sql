CREATE OR REPLACE FUNCTION is_complaint_overdue_open (
    p_complaint_id IN complaints.complaint_id%TYPE
) RETURN BOOLEAN
IS
    v_is_overdue v_complaint_detail.is_overdue%TYPE;
BEGIN
    SELECT is_overdue
      INTO v_is_overdue
      FROM v_complaint_detail
     WHERE complaint_id = p_complaint_id;

    RETURN v_is_overdue = 'Y';

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN FALSE;
END;
/

CREATE OR REPLACE PROCEDURE p_run_escalation_watchdog
AS
    v_escalated_count NUMBER := 0;
    v_new_level       complaints.escalation_level%TYPE;
BEGIN
    FOR c_rec IN (SELECT complaint_id, reference_no, escalation_level FROM complaints)
    LOOP
        IF is_complaint_overdue_open(c_rec.complaint_id) AND c_rec.escalation_level < 3 THEN

            v_new_level := c_rec.escalation_level + 1;

            UPDATE complaints
               SET escalation_level = v_new_level
             WHERE complaint_id = c_rec.complaint_id;

            INSERT INTO notifications (for_id, type, msg)
            VALUES (
                c_rec.complaint_id,
                'WARN',
                'Complaint ' || c_rec.reference_no ||
                ' is overdue - escalated to level ' || v_new_level
            );

            v_escalated_count := v_escalated_count + 1;
        END IF;
    END LOOP;

    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Watchdog finished. Complaints escalated: ' || v_escalated_count);
END;
/
BEGIN
    p_run_escalation_watchdog();
END;
