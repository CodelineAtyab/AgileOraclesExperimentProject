-- ---------------------------------------------------------------------------
-- 1. Reference / master data
-- ---------------------------------------------------------------------------
CREATE TABLE departments (
  dept_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dept_code  VARCHAR2(20)  NOT NULL UNIQUE,
  dept_name  VARCHAR2(100) NOT NULL,
  email_box  VARCHAR2(150),
  is_active  CHAR(1) DEFAULT 'Y' NOT NULL
             CONSTRAINT ck_dept_active CHECK (is_active IN ('Y','N'))
);

CREATE TABLE agents (
  agent_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  agent_name     VARCHAR2(100) NOT NULL,
  email          VARCHAR2(150) NOT NULL UNIQUE,
  dept_id        NUMBER        NOT NULL REFERENCES departments(dept_id),
  max_open_cases NUMBER(3) DEFAULT 10 NOT NULL,
  is_active      CHAR(1)   DEFAULT 'Y' NOT NULL
                 CONSTRAINT ck_agent_active CHECK (is_active IN ('Y','N'))
);

CREATE TABLE categories (
  category_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_code    VARCHAR2(30)  NOT NULL UNIQUE,
  category_name    VARCHAR2(100) NOT NULL,
  dept_id          NUMBER        NOT NULL REFERENCES departments(dept_id),
  default_priority VARCHAR2(10)  DEFAULT 'MEDIUM' NOT NULL
                   CONSTRAINT ck_cat_priority
                   CHECK (default_priority IN ('LOW','MEDIUM','HIGH','CRITICAL')),
  sla_hours        NUMBER(5)     NOT NULL,
  is_active        CHAR(1) DEFAULT 'Y' NOT NULL
                   CONSTRAINT ck_cat_active CHECK (is_active IN ('Y','N'))
);

CREATE TABLE customers (
  customer_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name   VARCHAR2(120) NOT NULL,
  email       VARCHAR2(150) NOT NULL UNIQUE,
  phone       VARCHAR2(20),
  tier        VARCHAR2(10) DEFAULT 'STANDARD' NOT NULL
              CONSTRAINT ck_cust_tier CHECK (tier IN ('STANDARD','PREMIUM','VIP')),
  created_at  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- ---------------------------------------------------------------------------
-- 2. Transactional table
-- ---------------------------------------------------------------------------
CREATE TABLE complaints (
  complaint_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference_no      VARCHAR2(20) UNIQUE,
  customer_id       NUMBER        NOT NULL REFERENCES customers(customer_id),
  category_id       NUMBER        NOT NULL REFERENCES categories(category_id),
  dept_id           NUMBER        REFERENCES departments(dept_id),
  assigned_agent_id NUMBER        REFERENCES agents(agent_id),
  subject           VARCHAR2(200) NOT NULL,
  description       CLOB,
  status            VARCHAR2(20)  DEFAULT 'NEW' NOT NULL
                    CONSTRAINT ck_cmp_status CHECK (status IN
                    ('NEW','ASSIGNED','IN_PROGRESS','PENDING_CUSTOMER',
                     'RESOLVED','CLOSED','REJECTED')),
  priority          VARCHAR2(10)  DEFAULT 'MEDIUM' NOT NULL
                    CONSTRAINT ck_cmp_priority CHECK (priority IN
                    ('LOW','MEDIUM','HIGH','CRITICAL')),
  escalation_level  NUMBER(1)     DEFAULT 0 NOT NULL
                    CONSTRAINT ck_cmp_esc CHECK (escalation_level BETWEEN 0 AND 3),
  source_channel    VARCHAR2(20)  DEFAULT 'WEB' NOT NULL,
  created_at        TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  due_at            TIMESTAMP,
  resolved_at       TIMESTAMP,
  closed_at         TIMESTAMP,
  created_by        VARCHAR2(50)  DEFAULT USER NOT NULL,
  updated_at        TIMESTAMP,
  updated_by        VARCHAR2(50)
);

-- ---------------------------------------------------------------------------
-- 3. Tables the challenge writes to
-- ---------------------------------------------------------------------------
CREATE TABLE notifications (
  id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  for_id NUMBER,
  type   VARCHAR2(10),
  msg    VARCHAR2(200)
);

CREATE TABLE complaint_audit (
  audit_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  complaint_id NUMBER       NOT NULL,
  reference_no VARCHAR2(20),
  action       VARCHAR2(10) NOT NULL
               CONSTRAINT ck_audit_action CHECK (action IN ('INSERT','UPDATE','DELETE')),
  column_name  VARCHAR2(30),
  old_value    VARCHAR2(4000),
  new_value    VARCHAR2(4000),
  changed_by   VARCHAR2(50) DEFAULT USER NOT NULL,
  changed_at   TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL
);

-- ---------------------------------------------------------------------------
-- 4. View used by the "is overdue" hint
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW v_complaint_detail AS
SELECT c.complaint_id,
       c.reference_no,
       cu.full_name    AS customer_name,
       cu.email        AS customer_email,
       cu.tier         AS customer_tier,
       cat.category_code,
       cat.category_name,
       cat.sla_hours,
       d.dept_code,
       d.dept_name,
       a.agent_name,
       c.subject,
       c.status,
       c.priority,
       c.escalation_level,
       c.created_at,
       c.due_at,
       c.resolved_at,
       CASE WHEN c.status NOT IN ('RESOLVED','CLOSED','REJECTED')
             AND c.due_at < SYSTIMESTAMP THEN 'Y' ELSE 'N' END AS is_overdue
FROM   complaints c
JOIN   customers  cu  ON cu.customer_id = c.customer_id
JOIN   categories cat ON cat.category_id = c.category_id
LEFT   JOIN departments d ON d.dept_id  = c.dept_id
LEFT   JOIN agents      a ON a.agent_id = c.assigned_agent_id;

