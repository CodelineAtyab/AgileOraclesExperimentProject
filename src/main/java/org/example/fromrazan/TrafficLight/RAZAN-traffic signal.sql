--3.Create START_TRAFFIC_SIGNAL
--purpose of this procedure is:
--When the trigger tells it that a new signal was inserted, it creates a Scheduler job dedicated to that signal.

--3.1 Create the procedure
CREATE OR REPLACE PROCEDURE start_traffic_signal (
    p_signal_id IN NUMBER
)
IS
    PRAGMA AUTONOMOUS_TRANSACTION;

    v_job_name VARCHAR2(100);

BEGIN

    -- Create a predictable job name for this signal
    v_job_name := 'TRAFFIC_SIGNAL_JOB_' || p_signal_id;


    -- Create Scheduler job
    DBMS_SCHEDULER.CREATE_JOB (
        job_name        => v_job_name,

        job_type        => 'PLSQL_BLOCK',

        job_action      =>
            'BEGIN process_traffic_signal(' || p_signal_id || '); END;',

        start_date      => SYSTIMESTAMP,

        repeat_interval => 'FREQ=SECONDLY;INTERVAL=1',

        enabled         => TRUE,

        auto_drop       => FALSE
    );


    COMMIT;


EXCEPTION

    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;

END;
/


