--2.Create the procedure:
CREATE OR REPLACE PROCEDURE process_traffic_signal (
    p_signal_id IN NUMBER
)
IS
    PRAGMA AUTONOMOUS_TRANSACTION;

    v_state        traffic_signals.state%TYPE;
    v_last_changed traffic_signals.last_changed_at%TYPE;
    v_elapsed      NUMBER;
    v_new_state    traffic_signals.state%TYPE;

BEGIN

    SELECT state, last_changed_at
    INTO v_state, v_last_changed
    FROM traffic_signals
    WHERE signal_id = p_signal_id
    FOR UPDATE;


    -- Calculate elapsed time in seconds
    v_elapsed :=
          EXTRACT(DAY    FROM (SYSTIMESTAMP - v_last_changed)) * 86400
        + EXTRACT(HOUR   FROM (SYSTIMESTAMP - v_last_changed)) * 3600
        + EXTRACT(MINUTE FROM (SYSTIMESTAMP - v_last_changed)) * 60
        + EXTRACT(SECOND FROM (SYSTIMESTAMP - v_last_changed));


    -- RED → YELLOW after 10 seconds
    IF v_state = 'RED' AND v_elapsed >= 10 THEN

        v_new_state := 'YELLOW';


    -- YELLOW → GREEN after 5 seconds
    ELSIF v_state = 'YELLOW' AND v_elapsed >= 5 THEN

        v_new_state := 'GREEN';


    -- GREEN → RED after 10 seconds
    ELSIF v_state = 'GREEN' AND v_elapsed >= 10 THEN

        v_new_state := 'RED';


    ELSE

        v_new_state := NULL;

    END IF;


    -- Update the state if a transition is required
    IF v_new_state IS NOT NULL THEN

        UPDATE traffic_signals
        SET state = v_new_state,
            last_changed_at = SYSTIMESTAMP
        WHERE signal_id = p_signal_id;

    END IF;


    COMMIT;


EXCEPTION

    WHEN NO_DATA_FOUND THEN
        COMMIT;

    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;

END;
